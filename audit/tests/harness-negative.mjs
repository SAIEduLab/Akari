import fs from 'node:fs';
import assert from 'node:assert/strict';
import {verify,verifyAuthority} from '../lib/verify-test-results.mjs';
import {withBrowser,pageFor,externalReports} from '../lib/product-test-host.mjs';
const [browserPath,reportPath,output='audit-evidence/harness-negative.json']=process.argv.slice(2);
const report=JSON.parse(fs.readFileSync(reportPath)),manifest=JSON.parse(fs.readFileSync('audit/manifests/product-tests.json'));
verifyAuthority(manifest);verify(report,manifest,report.snapshot);
const results=[];
const negative=(id,mutate)=>{const r=structuredClone(report);mutate(r);assert.throws(()=>verify(r,manifest,report.snapshot),id);results.push({id,pass:true});};
negative('missing ID',r=>{r.suites[0].results.pop();});
negative('duplicate ID',r=>{r.suites[0].results[1]=r.suites[0].results[0];});
negative('extra ID',r=>{r.suites[0].results.push({id:'FAKE',pass:true,detail:'PASS'});});
negative('missing suite',r=>r.suites.pop());
negative('duplicate suite',r=>r.suites.push(r.suites[0]));
negative('empty suite',r=>r.suites[0].results=[]);
negative('missing environment',r=>delete r.suites[0].environment);
negative('wrong environment',r=>r.environment='node');
negative('exception status',r=>r.suites[0].status='ERROR');
negative('timeout status',r=>r.suites[0].status='TIMEOUT');
negative('false pass',r=>r.suites[0].results[0].pass=false);
negative('contradictory status',r=>r.suites[0].results[0].status='FAIL');
negative('forged summary',r=>r.total=1);
negative('forged aggregate',r=>r.results=[]);
negative('missing snapshot',r=>delete r.snapshot);
negative('changed product hash',r=>r.snapshot.productSha256='0'.repeat(64));
negative('incomplete',r=>r.complete=false);
const m=structuredClone(manifest);m.suites[0].ids.pop();assert.throws(()=>verify(report,m,report.snapshot));results.push({id:'shrunk manifest',pass:true});
await assert.rejects(()=>withBrowser('',async()=>{}),/environment missing/);results.push({id:'missing browser executable',pass:true});
await withBrowser(browserPath,async browser=>{
 await assert.rejects(()=>externalReports(browser,'Akari.html',[]),/Empty/);
 await assert.rejects(()=>externalReports(browser,'Akari.html',['runMissingTests']),/ENOENT/);
 await assert.rejects(()=>pageFor(browser,'Akari.html',p=>p.evaluate(()=>{throw Error('negative registration exception');})),/negative registration exception/);
 await assert.rejects(()=>pageFor(browser,'Akari.html',p=>p.evaluate('(() => { invalid syntax !!! })()')),/Unexpected/);
});
results.push(...['empty registration','missing suite file','registration exception','registration syntax error'].map(id=>({id,pass:true})));
await assert.rejects(()=>withBrowser(browserPath,async browser=>pageFor(browser,'Akari.html',p=>p.evaluate(()=>new Promise(()=>{}))),1000),/timeout/);
results.push({id:'actual nonsettling browser evaluation timeout and cleanup',pass:true});
fs.writeFileSync(output,JSON.stringify({status:'PASS',results},null,2)+'\n');console.log('Harness negatives: '+results.length+' PASS');
